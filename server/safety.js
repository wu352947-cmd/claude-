// 心理危机信号的保守检测：命中时不调用模型，直接给出固定的关怀信与求助渠道。
// 宁可多提示一次，也不要漏掉。关键词表应由专业人士定期复核。
const PATTERNS = [
  /想死/, /去死/, /不想活/, /活不下去/, /活着没(有)?意思/, /活着(好|太)累/, /自杀/, /轻生/, /寻死/,
  /结束(自己的)?生命/, /了结(自己|一切)/, /割腕/, /跳楼/, /跳河/, /安眠药.{0,6}(吃|攒)/, /(吃|攒).{0,6}安眠药/,
  /遗书/, /消失(就好|算了|掉)/, /不想(再)?醒来/, /伤害自己/, /自残/
];

export function crisisSignal(text) {
  const t = String(text || '').replace(/\s+/g, '');
  return PATTERNS.some(p => p.test(t));
}

